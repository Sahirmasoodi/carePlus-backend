const express = require("express");
const cors = require("cors");
const helmet = require("helmet");
const cookieParser = require("cookie-parser");
const rateLimit = require("express-rate-limit");
const publicRoutes = require("./routes/publicRoutes");
const authRoutes = require("./routes/authRoutes");
const platformRoutes = require("./routes/platformRoutes");
const clinicRoutes = require("./routes/clinicRoutes");
const { notFound, errorHandler } = require("./middleware/errorHandler");

const app = express();
app.disable("x-powered-by");
app.use(helmet({ crossOriginResourcePolicy: { policy: "cross-origin" } }));
app.use(cors({ origin: (process.env.CLIENT_URL || "http://localhost:5173").split(",").map(x => x.trim()), credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: true, limit: "1mb" }));
app.use(cookieParser());
app.get("/health", (req, res) => res.json({ success: true, service: "careplus-api", timestamp: new Date().toISOString() }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 100, standardHeaders: "draft-8", legacyHeaders: false }), authRoutes);
app.use("/api/public", publicRoutes);
app.use("/api/platform", platformRoutes);
app.use("/api/clinic", clinicRoutes);
app.use(notFound);
app.use(errorHandler);
module.exports = app;
